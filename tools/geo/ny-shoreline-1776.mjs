// ---------------- helpers ----------------
// Centripetal Catmull-Rom through the points (lon/lat, lon scaled by cos(lat) so curves are round on the map).
// Pieces are subdivided to about `step` degrees.
const K = Math.cos(40.75 * Math.PI / 180);
function spline(pts, closed = false, step = 0.00035) {
  const n = pts.length;
  if (n < 3) return pts.slice();
  const P = i => closed ? pts[(i + n) % n] : pts[Math.max(0, Math.min(n - 1, i))];
  const out = [];
  const segs = closed ? n : n - 1;
  for (let i = 0; i < segs; i++) {
    const p0 = P(i - 1), p1 = P(i), p2 = P(i + 1), p3 = P(i + 2);
    const d = (a, b) => Math.max(1e-9, Math.sqrt(Math.hypot((b[0] - a[0]) * K, b[1] - a[1])));
    const t1 = d(p0, p1), t2 = t1 + d(p1, p2), t3 = t2 + d(p2, p3);
    const len = Math.hypot((p2[0] - p1[0]) * K, p2[1] - p1[1]);
    const m = Math.max(1, Math.ceil(len / step));
    for (let j = 0; j < m; j++) {
      const t = t1 + (t2 - t1) * j / m;
      const L = (a, b, ta, tb) => [0, 1].map(k => ta === tb ? a[k] : ((tb - t) * a[k] + (t - ta) * b[k]) / (tb - ta));
      const A1 = L(p0, p1, 0, t1), A2 = L(p1, p2, t1, t2), A3 = L(p2, p3, t2, t3);
      const B1 = L(A1, A2, 0, t2), B2 = L(A2, A3, t1, t3);
      out.push(L(B1, B2, t1, t2));
    }
  }
  if (!closed) out.push(pts[n - 1]);
  return out;
}
