  // Shift point labels that would be clipped by the map frame back inside it.
  // Labels overlapping the north arrow or scale box (`furn`) are moved off them by the shortest way.
  function keepLabelsInside(svg, VW, VH, pad, furn) {
    // shift that brings box b inside the frame and off the north arrow and scale box
    const place = b => {
      let dx = 0, dy = 0;
      if (b.x < pad) dx = pad - b.x; else if (b.x + b.width > VW - pad) dx = VW - pad - b.x - b.width;
      if (b.y < pad) dy = pad - b.y; else if (b.y + b.height > VH - pad) dy = VH - pad - b.y - b.height;
      const lb = { x: b.x + dx, y: b.y + dy, width: b.width, height: b.height };
      furn.forEach(f => {
        const m = 2;
        if (lb.x > f.x + f.width + m || lb.x + lb.width < f.x - m || lb.y > f.y + f.height + m || lb.y + lb.height < f.y - m) return;
        const opts = [
          [f.x - m - (lb.x + lb.width), 0], [f.x + f.width + m - lb.x, 0],
          [0, f.y - m - (lb.y + lb.height)], [0, f.y + f.height + m - lb.y],
        ].filter(([ox, oy]) => lb.x + ox >= pad && lb.x + lb.width + ox <= VW - pad && lb.y + oy >= pad && lb.y + lb.height + oy <= VH - pad);
        if (!opts.length) return;
        const [ox, oy] = opts.reduce((a, c) => Math.hypot(...c) < Math.hypot(...a) ? c : a);
        dx += ox; dy += oy; lb.x += ox; lb.y += oy;
      });
      return [dx, dy];
    };
    svg.selectAll('.hm-root text.hm-lbl').each(function () {
      if (this.querySelector('textPath')) return slidePathLabel(this, VW, VH, pad, furn);
      let b = this.getBBox();
      // measure the rotated box for rotated labels
      const m = /rotate\(([-\d.]+),([-\d.]+),([-\d.]+)\)/.exec(this.getAttribute('transform') || '');
      if (m) {
        const a = +m[1] * Math.PI / 180, cx = +m[2], cy = +m[3];
        const pts = [[b.x, b.y], [b.x + b.width, b.y], [b.x, b.y + b.height], [b.x + b.width, b.y + b.height]]
          .map(([x, y]) => [cx + (x - cx) * Math.cos(a) - (y - cy) * Math.sin(a), cy + (x - cx) * Math.sin(a) + (y - cy) * Math.cos(a)]);
        const xs = pts.map(q => q[0]), ys = pts.map(q => q[1]);
        b = { x: Math.min(...xs), y: Math.min(...ys), width: Math.max(...xs) - Math.min(...xs), height: Math.max(...ys) - Math.min(...ys) };
      }
      let [dx, dy] = place(b);
      // A label pushed onto its own symbol is mirrored to the other side of the symbol instead.
      const ax = +this.dataset.ax, ay = +this.dataset.ay, rx = +this.dataset.rx, ry = +this.dataset.ry;
      const onSym = (ox, oy) => !(b.x + ox > ax + rx || b.x + b.width + ox < ax - rx || b.y + oy > ay + ry || b.y + b.height + oy < ay - ry);
      if ((dx || dy) && !m && this.dataset.ax != null && onSym(dx, dy)) {
        const mx = 2 * ax - 2 * b.x - b.width, my = 2 * ay - 2 * b.y - b.height;
        let best = null;
        [[mx, 0], [0, my], [mx, my]].forEach(([cx, cy]) => {
          const [sx, sy] = place({ x: b.x + cx, y: b.y + cy, width: b.width, height: b.height });
          const score = (onSym(cx + sx, cy + sy) ? 1e4 : 0) + Math.hypot(sx, sy);
          if (!best || score < best[0]) best = [score, cx + sx, cy + sy];
        });
        if (best[0] < 1e4) [dx, dy] = [best[1], best[2]];
      }
      if (dx || dy) {
        const tr = this.getAttribute('transform') || '';
        this.setAttribute('transform', `translate(${dx},${dy}) ${tr}`);
      }
    });
  }


  // Centroid if it falls inside the polygon, else the inside point farthest from its edges
  // (grid search), so labels of concave areas stay inside them.
  function interiorPoint(pts) {
    const c = d3.polygonCentroid(pts);
    if (d3.polygonContains(pts, c)) return c;
    const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
    const x0 = Math.min(...xs), y0 = Math.min(...ys), sx = (Math.max(...xs) - x0) / 40, sy = (Math.max(...ys) - y0) / 40;
    const segDist = (p, a, b) => {
      const dx = b[0] - a[0], dy = b[1] - a[1], L = dx * dx + dy * dy;
      const t = L ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / L)) : 0;
      return Math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy);
    };
    let best = c, bestD = -1;
    for (let i = 0; i <= 40; i++) for (let j = 0; j <= 40; j++) {
      const p = [x0 + i * sx, y0 + j * sy];
      if (!d3.polygonContains(pts, p)) continue;
      const d = Math.min(...pts.map((q, k) => segDist(p, q, pts[(k + 1) % pts.length])));
      if (d > bestD) { bestD = d; best = p; }
    }
    return best;
  }

  // Labels along a path can't be shifted freely: slide them along the path (startOffset) until
  // they are inside the frame and off the north arrow and scale box, if such a spot exists.
  function slidePathLabel(t, VW, VH, pad, furn) {
    const tp = t.querySelector('textPath');
    let o0 = parseFloat(tp.getAttribute('startOffset'));
    // keep the whole label on its path (text past the path's ends isn't drawn)
    const L = document.getElementById(tp.getAttribute('href').slice(1)).getTotalLength();
    const w = tp.getComputedTextLength();
    const lo = Math.min(50, (w / 2 + 2) / L * 100), hi = 100 - lo;
    o0 = Math.max(lo, Math.min(hi, o0));
    tp.setAttribute('startOffset', o0 + '%');
    const bad = () => {
      const b = t.getBBox();
      let v = Math.max(0, pad - b.x) + Math.max(0, b.x + b.width - VW + pad) + Math.max(0, pad - b.y) + Math.max(0, b.y + b.height - VH + pad);
      furn.forEach(f => {
        const ox = Math.min(b.x + b.width, f.x + f.width) - Math.max(b.x, f.x), oy = Math.min(b.y + b.height, f.y + f.height) - Math.max(b.y, f.y);
        if (ox > 0 && oy > 0) v += Math.min(ox, oy);
      });
      return v;
    };
    let best = o0, bestV = bad();
    if (!bestV) return;
    for (let d = 4; d <= 45 && bestV; d += 4) for (const o of [o0 - d, o0 + d]) {
      if (o < lo || o > hi) continue;
      tp.setAttribute('startOffset', o + '%');
      const v = bad();
      if (v < bestV - 0.5) { best = o; bestV = v; }
      if (!v) break;
    }
    tp.setAttribute('startOffset', best + '%');
  }

  function starPath(x, y, r) {
    let d = '';
    for (let i = 0; i < 10; i++) {
      const a = -Math.PI / 2 + i * Math.PI / 5, rr = i % 2 ? r * 0.5 : r;
      d += (i ? 'L' : 'M') + (x + rr * Math.cos(a)).toFixed(1) + ',' + (y + rr * Math.sin(a)).toFixed(1);
    }
    return d + 'Z';
  }

